#!/usr/bin/env python3
"""Evaluation v2 (docs/PERSONA_EVAL_V2.md, user-approved 2026-08-13).

    python -m cooksim_bench.scoring.eval_v2 <report.json> --q1 2 --q2 2 --q3 2 [--write]

Four headline scores; a, b, c in {1,2,3} are the user's questionnaire answers (levels
low=1 / medium=2 / high=3). Every weighted score is stored RAW (the user's definition)
and NORMALIZED (comparable across users). Reads only the report; the one LLM-derived
input (suggestion quality) is taken from an existing judge block when present, else null.

    task_success       = engine verdict (1 won; graded partial credit; the hard gate)
    task_efficiency    = a*TT + c*CC          normalized: /(a+c)
    assistance_quality = b*(DT+DQ) + 2*SQ     normalized: /(2b+2)
    interaction_quality = exit_survey satisfaction/reuse, (x-1)/6, reported separately

Components (all in [0,1], null = not measured, never zero):
    TT = clip01(ref_ticks / ticks)            ref from --ref-ticks or bench/ref_ticks.json
    CC = 1 - clip01(T_interrupt / T_action)   T_interrupt = assistant speech time landing
                                              mid-action (pauses[] with costs_game_time
                                              False whose tick falls inside an action);
                                              T_action = episode speech+action span
    DT tier ladder: prevented 1.0; valid before outcome 0.9-0.5 by latency/window;
                    valid after outcome 0.3; correct-name-never-in-time 0.0
    DQ = 1 - (0.5*miss + 0.5*fa_norm)         fa budget: max(3, 3*ticks/100)
    SQ = (judge_1to10 - 1)/9                  from eval_qualitative: a flat judge_mean /
                                              judge_score / suggestion_quality if one is
                                              present, else the mean of the nested
                                              judge.scores sub-scores (what eval_judge.py
                                              actually writes)
"""
from __future__ import annotations
import argparse, json, os, shutil, sys

from cooksim.interact.checks import CORRECT_VERDICTS  # noqa: E402  (ONE definition of a correct flag)
from cooksim.interact import windows as windows_lib  # noqa: E402  (ONE definition of a grading window)


def clip01(x):
    return max(0.0, min(1.0, float(x)))


# ------------------------------------------------------------------ efficiency reference
# The docstring above has always promised `ref from --ref-ticks or bench/ref_ticks.json`,
# but nothing read the file: every episode scored with no explicit --ref-ticks silently got
# TT=None, so task_efficiency collapsed to CC alone and the `a` weight did nothing. The file
# is generated by python -m cooksim_bench.suite.gen_ref_ticks (clean reference plan, real executor, no LLM).
_REF_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                         "benchmark/ref_ticks.json")
_REF_CACHE = {}
_CASE_CELL = {}


def load_ref_ticks(path=None):
    path = path or _REF_PATH
    if path not in _REF_CACHE:
        try:
            _REF_CACHE[path] = json.load(open(path))
        except Exception:                                        # noqa: BLE001
            _REF_CACHE[path] = {}
    return _REF_CACHE[path]


def _cell_of_report(d):
    """A report does not carry its cell; the case file does. Resolve scenario -> cell."""
    if d.get("cell"):                                            # once the wiring adds it
        return d["cell"]
    if not _CASE_CELL:
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        for f in ("cases_newrecipes.json", "cases_intent.json", "cases_qa_auto.json"):
            try:
                blob = json.load(open(os.path.join(root, "tmp/interact_eval", f)))
            except Exception:                                    # noqa: BLE001
                continue
            top = blob.get("cell") if isinstance(blob, dict) else None
            for c in (blob if isinstance(blob, list) else blob.get("cases") or []):
                if c.get("name"):
                    _CASE_CELL[c["name"]] = c.get("cell") or top or ""
    return _CASE_CELL.get(d.get("scenario") or "", "")


def resolve_ref_ticks(d, explicit=None, cell=None, path=None):
    """explicit > named cell > the report's own cell. Returns None when unresolvable —
    TT then reads `not measured` rather than a fabricated 0, per this module's convention
    that a missing component is null and never zero."""
    if explicit:
        return explicit
    table = load_ref_ticks(path)
    key = cell or _cell_of_report(d)
    v = table.get(key)
    return float(v) if isinstance(v, (int, float)) else None


def task_success(d):
    if d.get("outcome") == "won":
        return 1.0
    if d.get("outcome") in ("fire", "burned"):
        return 0.0
    if d.get("aborted") and d.get("outcome") is None:
        return None                                  # not measured, never zero
    plate = d.get("plate_first_order") or []
    goal = [c for c, _ in (d.get("goal_contents") or [])] or None
    if goal:
        k = 0
        for want, got in zip(goal, plate):
            if want == got:
                k += 1
            else:
                break
        return k / len(goal)
    return 0.0 if plate is not None else None


def tt(d, ref_ticks):
    if not d.get("ticks") or not ref_ticks:
        return None
    return clip01(ref_ticks / d["ticks"])


def cc(d):
    """Conversation efficiency: 1 - interrupt/action time. Speech costs no game time, so
    both sides are measured in recorded speech-seconds vs episode tick-span (POLL-scaled
    seconds are consistent within an episode, which is all a ratio needs)."""
    pauses = d.get("pauses") or []
    if not d.get("ticks"):
        return None
    t_int = sum(p.get("ticks") or 0 for p in pauses
                if p.get("who") == "vlm" and not p.get("costs_game_time", True))
    t_act = d["ticks"]
    if t_act <= 0:
        return None
    return 1.0 - clip01(t_int / t_act)


def dt(d):
    if d.get("failed_at") == "injection_skipped" or d.get("injected_at") is None:
        return None
    if d.get("prevented"):
        return 1.0
    # F4e (2026-08-14 fix batch) MONOTONICITY. The ladder below charges the 0.3
    # "detected, but only after the fact" rate whenever `prevention_missed` is set. But
    # `prevention_missed` records that the PREVENTION GATE did not fire, not that the
    # error happened — and the plate verdict knows which. An episode where the injected
    # error was never committed and the assistant called it early therefore scored 0.3,
    # BELOW the 0.5 given to an identical episode whose flag came later and never armed
    # the gate at all: flagging earlier scored worse. Nothing was ever wrong with that
    # dish, so the outcome is prevention-equivalent and scores as prevention.
    flags = d.get("flags") or []
    if d.get("error_committed") is False and (
            d.get("flagged_valid") or d.get("prevented")
            or any((f.get("verdict") in CORRECT_VERDICTS or f.get("verdict") == "prevented")
                   for f in flags)):
        return 1.0
    if d.get("flagged_valid"):
        lat, win = d.get("latency"), d.get("window")
        # The 0.3 after-branch is only honest when the error ACTUALLY committed before
        # the flag; `error_committed is False` has already returned 1.0 above.
        if windows_lib.window_rule(d) == windows_lib.LIVE:
            # LIVE WINDOWS (2026-09-20): the window already closes at the commit, so the
            # post-hoc rung is decided by the CALL's own tick, not by whether the cook's
            # accept came too late to save the dish.
            tf = [f.get("t") for f in (d.get("flags") or [])
                  if f.get("verdict") in CORRECT_VERDICTS and isinstance(f.get("t"), (int, float))]
            after = bool(win and tf and min(tf) > win[1]) or (
                not tf and any(f.get("verdict") == "late" for f in (d.get("flags") or [])))
        else:
            after = (d.get("prevention_missed") is not None
                     or (d.get("released_reason") or "").endswith("after_outcome"))
        if after:
            return 0.3
        if lat is not None and win and (win[1] - win[0]) > 0:
            return 0.9 - 0.4 * clip01(lat / (win[1] - win[0]))
        return 0.7
    if any(f.get("verdict") in ("early_correct", "early_alias", "alias_in_window")
           for f in d.get("flags") or []):
        return 0.5                                   # right call, credit denied by window
    return 0.0


def dq(d):
    if d.get("failed_at") == "injection_skipped" or d.get("injected_at") is None:
        return None
    hit = 1 if (d.get("flagged_valid") or d.get("prevented") or any(
        f.get("verdict") in CORRECT_VERDICTS for f in d.get("flags") or [])) else 0
    fa = len(d.get("false_positives") or [])
    budget = max(3.0, 3.0 * (d.get("ticks") or 100) / 100.0)
    fa_norm = clip01(fa / budget)
    return 1.0 - (0.5 * (1 - hit) + 0.5 * fa_norm)


def _to_sq(v):
    """A judge value on either scale: 1-10 becomes (v-1)/9, an already-[0,1] value stays."""
    return clip01((v - 1) / 9) if v > 1 else clip01(v)


def sq(d):
    """Suggestion quality from the judge block, in whichever shape the judge wrote it.

    `python -m cooksim_bench.scoring.eval_judge` stores the six sub-scores nested under `judge.scores` and writes
    NO top-level mean, so reading only the flat keys returned null on every report that had
    a perfectly good judge result. That is not a harmless gap: SQ is the only term in
    assistance_quality that grades DELIVERY, so dropping it systematically flatters the
    score. The v2 sweep's classic_expert published 0.915 while its own user rated the
    assistant 2/7 and complained it would not stop interrupting.

    The flat keys are kept FIRST as fallbacks: they are an explicit summary when a writer
    provides one, and older reports carry them.
    """
    q = (d.get("eval_qualitative") or {})
    for k in ("judge_mean", "judge_score", "suggestion_quality"):
        v = q.get(k)
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            return _to_sq(v)
    scores = ((q.get("judge") or {}).get("scores")) or {}
    vals = [v for v in scores.values()
            if isinstance(v, (int, float)) and not isinstance(v, bool)]
    if vals:
        return _to_sq(sum(vals) / len(vals))
    return None


def iq(d):
    ex = d.get("exit_survey") or {}
    out = {}
    for k in ("satisfaction", "reuse"):
        v = ex.get(k)
        out[k] = clip01((v - 1) / 6) if isinstance(v, (int, float)) else None
    out["elicitation"] = ex.get("elicitation")
    return out


def wmean(pairs):
    """Weighted mean over non-null components: [(weight, value), ...]."""
    live = [(w, v) for w, v in pairs if v is not None]
    if not live:
        return None, None
    raw = sum(w * v for w, v in live)
    return raw, raw / sum(w for w, _ in live)


def score(d, a, b, c, ref_ticks=None):
    TT, CC, DT, DQ, SQ = tt(d, ref_ticks), cc(d), dt(d), dq(d), sq(d)
    te_raw, te_norm = wmean([(a, TT), (c, CC)])
    aq_raw, aq_norm = wmean([(b, DT), (b, DQ), (2, SQ)])
    return {
        "schema": "eval2-v1",
        "weights": {"a": a, "b": b, "c": c},
        "task_success": task_success(d),
        "task_efficiency": {"raw": te_raw, "normalized": te_norm,
                            "TT": TT, "CC": CC},
        "assistance_quality": {"raw": aq_raw, "normalized": aq_norm,
                               "DT": DT, "DQ": DQ, "SQ": SQ},
        "interaction_quality": iq(d),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("reports", nargs="+")
    ap.add_argument("--q1", type=int, required=True, choices=[1, 2, 3])
    ap.add_argument("--q2", type=int, required=True, choices=[1, 2, 3])
    ap.add_argument("--q3", type=int, required=True, choices=[1, 2, 3])
    ap.add_argument("--ref-ticks", type=float, default=None)
    ap.add_argument("--cell", default=None,
                    help="cell key for bench/ref_ticks.json (default: from the case file)")
    ap.add_argument("--ref-file", default=None)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    for path in args.reports:
        d = json.load(open(path))
        ref = resolve_ref_ticks(d, args.ref_ticks, args.cell, args.ref_file)
        ev = score(d, args.q1, args.q2, args.q3, ref)
        ts = ev["task_success"]
        te = ev["task_efficiency"]["normalized"]
        aq = ev["assistance_quality"]["normalized"]
        print(f"{os.path.basename(path)}  ref_ticks={ref}  success={ts}  "
              f"efficiency={None if te is None else round(te, 3)}  "
              f"assistance={None if aq is None else round(aq, 3)}  "
              f"IQ={ev['interaction_quality']}")
        if args.write:
            shutil.copy(path, path + ".bak")
            d["eval_v2"] = ev
            json.dump(d, open(path, "w"), indent=1)


if __name__ == "__main__":
    sys.exit(main())
