def _adp_toggle(st, d, event):
    """Per the manual, turning ADP on runs a confirm step that reviews the
    recovery requirement — model that as an iOS alert, not a silent flip."""
    from .settings_engine import sget, sset
    if sget(d, "spec.icloud.adp"):
        sset(d, "spec.icloud.adp", False)
        return None
    st.dialog = {
        "screen": "settings.dlg_adp",
        "title": "Turn On Advanced Data Protection?",
        "body": "Apple will no longer be able to help you recover your "
                "iCloud data. Your Recovery Contact (Dana Bennett) will be "
                "the only way back in if you lose access.",
        "buttons": [("Turn On", ("saction", ("adp_confirm",)), "filled"),
                    ("Cancel", ("close_dialog",), "text")],
        "dismissable": True,
    }
    return None


def _adp_confirm(st, d, event):
    from .settings_engine import sset
    sset(d, "spec.icloud.adp", True)
    st.dialog = None
    return None


ACTIONS = {"adp_toggle": _adp_toggle, "adp_confirm": _adp_confirm}
