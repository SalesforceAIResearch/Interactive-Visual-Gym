"""The iPhone Settings tree, as data.

Every screen here is interpreted by settings_engine into a real iOS screen, so
covering "everything in the manual" is a matter of adding rows. Task-critical
and genuinely-dynamic screens (Wi-Fi list, Location per app, Storage, per-app
pages) stay as custom methods in settings_app; this file fills in the enormous
static breadth (Accessibility, Camera, Focus, Face ID & Passcode, About,
Keyboard, Wallet, App Store, …) that a real iPhone has.
"""
from __future__ import annotations

# ---- row shorthands ------------------------------------------------------
def nav(label, target, icon="", sub=None, subval=None):
    r = {"t": "nav", "label": label, "target": "settings." + target}
    if icon:
        r["icon"] = icon
    if sub is not None:
        r["sub"] = sub
    if subval is not None:
        r["subval"] = subval
    return r


def link(label, target, icon="", sub=None):
    r = {"t": "link", "label": label, "target": target}
    if icon:
        r["icon"] = icon
    if sub is not None:
        r["sub"] = sub
    return r


def tog(label, skey, sub=None, icon="", disable_if=None):
    r = {"t": "toggle", "label": label, "skey": skey}
    if sub is not None:
        r["sub"] = sub
    if icon:
        r["icon"] = icon
    if disable_if:
        r["disable_if"] = disable_if
    return r


def ch(label, skey, icon=""):
    r = {"t": "choice", "label": label, "skey": skey}
    if icon:
        r["icon"] = icon
    return r


def sld(label, skey):
    return {"t": "slider", "label": label, "skey": skey}


def fld(label, skey, hint="", mask=False, kb="text"):
    return {"t": "field", "label": label, "skey": skey, "hint": hint,
            "mask": mask, "kb": kb}


def info(label, val=None, valkey=None, icon=""):
    r = {"t": "info", "label": label}
    if val is not None:
        r["val"] = val
    if valkey is not None:
        r["valkey"] = valkey
    if icon:
        r["icon"] = icon
    return r


def action(label, event, style="text"):
    return {"t": "action", "label": label, "event": event, "style": style}


def txt(t, h=None):
    r = {"t": "text", "text": t}
    if h:
        r["h"] = h
    return r


def sec(header, *rows):
    return {"header": header, "rows": list(rows)}


def screen(title, *sections, back=None):
    s = {"title": title, "sections": list(sections)}
    if back:
        s["back"] = back
    return s


