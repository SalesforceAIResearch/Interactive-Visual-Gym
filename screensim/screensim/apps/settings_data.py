    langs = ["Apple Dictionary", "Chinese (Simplified) – English", "Dutch",
             "English (UK)", "English (US)", "French", "German", "Hebrew",
             "Italian", "Japanese", "Korean", "Portuguese", "Russian", "Spanish",
             "Thai", "Turkish"]
    dl = {"English (US)", "Apple Dictionary"}
